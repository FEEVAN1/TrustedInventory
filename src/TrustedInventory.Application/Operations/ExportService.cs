public sealed record ExportJobDto(
    Guid Id, int Version, DateTimeOffset CreatedAt, string CreatedBy, DateTimeOffset UpdatedAt, ExportType Type, ExportStatus Status, ExportFilters Filters,
    StreamRange? StreamRange, ExportManifest? Manifest, DateTimeOffset? CompletedAt, DateTimeOffset? RetainUntil, string? FailureReason) : IVersioned;

public sealed record ExportFilter(ExportType? Type, ExportStatus? Status);

public sealed class CreateExportValidator : AbstractValidator<CreateExport>
{
    public CreateExportValidator()
    {
        RuleFor(x => x.Filters).NotNull();
        RuleFor(x => x.Filters.To).GreaterThan(x => x.Filters.From).When(x => x.Filters is { From: not null, To: not null })
            .WithMessage("The range ends after it starts.").OverridePropertyName("filters.to");
    }
}

/// <summary>
/// Exports (AUD-004, NFR-EXPORTS, TEN-005, DEC-061): queued here, generated by the worker, downloaded through a link that
/// is authorised again at download time.
/// </summary>
public sealed class ExportService(ITenantUnitOfWork uow, ICallerAccessor callers, ICursorCodec cursors, IObjectStore store, IDownloadLinks links,
    IValidator<CreateExport> validator)
{
    /// <summary>Proposed runtime budget (SOP-001, DEC-073): two unfinished exports per tenant.</summary>
    public const int MaxConcurrent = 2;

    public Task<ExportJobDto> CreateAsync(CreateExport cmd, CancellationToken ct)
    {
        var caller = callers.Caller;
        caller.Require(Permissions.ExportsCreate);
        validator.ValidateOrThrow(cmd);
        if (cmd.Type == ExportType.Traceability)
            throw AppException.Validation("type", "Traceability exports arrive with the medical milestone (M5).");
        // The tenant archive holds every record of the workspace: owner only, at creation and again at download (LFC-003).
        if (cmd.Type == ExportType.TenantArchive && !caller.IsOwner)
            throw AppException.Forbidden("Only the workspace owner can export the tenant archive.");
        return uow.WriteAsync(async (s, c) =>
        {
            // SOP-001: counted under a tenant-scoped advisory lock so two concurrent requests cannot both pass. The archive export a
            // workspace closure queues is created separately and never refused (DEC-070).
            var lockKey = $"exports:{caller.TenantId:N}";
            await s.Db.Database.ExecuteSqlAsync($"SELECT pg_advisory_xact_lock(hashtextextended({lockKey}, 0))", c);
            var active = await s.Db.Set<ExportJob>().CountAsync(j => j.Status == ExportStatus.Queued || j.Status == ExportStatus.Running, c);
            if (active >= MaxConcurrent)
                throw AppException.RateLimited(
                    $"Your workspace already has {active} exports in progress (limit {MaxConcurrent}). Retry when one completes.", TimeSpan.FromSeconds(60));
            var filter = JsonSerializer.SerializeToNode(cmd.Filters, JsonDefaults.Options)!;
            var job = ExportJob.Queue(caller.TenantId, cmd.Type, filter.ToJsonString(), SHA256.HashData(Encoding.UTF8.GetBytes(CanonicalJson.Serialize(filter))),
                caller.Subject, s.Now);
            s.Db.Add(job);
            var dto = Dto(job);
            s.Audit(new AuditEntry("ExportRequested", "ExportJob", job.Id, job.Version, null, null, dto));
            await s.Db.SaveChangesAsync(c);
            return dto;
        }, ct);
    }

    public Task<ExportJobDto> GetAsync(Guid id, CancellationToken ct)
    {
        callers.Caller.Require(Permissions.ExportsCreate);
        return uow.ReadAsync(async (s, c) =>
            Dto(await s.Db.Set<ExportJob>().AsNoTracking().SingleOrDefaultAsync(j => j.Id == id, c) ?? throw AppException.NotFound("Export")), ct);
    }

    public Task<Page<ExportJobDto>> ListAsync(ExportFilter filter, PageRequest page, CancellationToken ct)
    {
        callers.Caller.Require(Permissions.ExportsCreate);
        return uow.ReadAsync(async (s, c) =>
        {
            var query = s.Db.Set<ExportJob>().AsNoTracking();
            if (filter.Type is { } type)
                query = query.Where(j => j.Type == type);
            if (filter.Status is { } status)
                query = query.Where(j => j.Status == status);
            return await query.ToPageAsync(page, $"exports|{filter.Type}|{filter.Status}", cursors, Dto, c);
        }, ct);
    }

    public Task<DownloadLinkDto> LinkAsync(Guid id, CancellationToken ct)
    {
        var caller = callers.Caller;
        caller.Require(Permissions.ExportsCreate);
        return uow.WriteAsync(async (s, c) =>
        {
            var job = await s.Db.Set<ExportJob>().AsNoTracking().SingleOrDefaultAsync(j => j.Id == id, c) ?? throw AppException.NotFound("Export");
            if (job.Type == ExportType.TenantArchive && !caller.IsOwner)
                throw AppException.NotFound("Export");
            if (job.Status != ExportStatus.Completed || job.RetainUntil <= s.Now)
                throw AppException.InvalidState($"The export is {job.Status}; only a completed, retained export can be downloaded.");
            var expires = s.Now + IDownloadLinks.MaxLifetime;
            var token = links.Issue(caller.TenantId, DownloadKind.Export, id, caller.Subject, expires);
            s.Audit(new AuditEntry("ExportLinkIssued", "ExportJob", id, job.Version, null, null, new { exportId = id, expiresAt = expires }));
            await s.Db.SaveChangesAsync(c);
            return new DownloadLinkDto($"/api/v1/exports/{id}/download?token={Uri.EscapeDataString(token)}", expires);
        }, ct);
    }

    public Task<DownloadedFile> DownloadAsync(Guid id, string token, CancellationToken ct)
    {
        var caller = callers.Caller;
        caller.Require(Permissions.ExportsCreate);
        return uow.WriteAsync(async (s, c) =>
        {
            if (!links.IsValid(token, caller.TenantId, DownloadKind.Export, id, caller.Subject, s.Now))
                throw AppException.NotFound("Download");
            var job = await s.Db.Set<ExportJob>().AsNoTracking().SingleOrDefaultAsync(j => j.Id == id, c);
            if (job is not { Status: ExportStatus.Completed, ObjectKey: { } key } || job.RetainUntil <= s.Now)
                throw AppException.NotFound("Download");
            if (job.Type == ExportType.TenantArchive && !caller.IsOwner)
                throw AppException.NotFound("Download");
            var content = await store.GetAsync(key, c) ?? throw AppException.NotFound("Download");
            s.Audit(new AuditEntry("ExportDownloaded", "ExportJob", id, job.Version, null, null, new { exportId = id, bytes = content.Length }));
            await s.Db.SaveChangesAsync(c);
            return job.Type == ExportType.TenantArchive
                ? new DownloadedFile($"tenant-archive-{id:N}.zip", "application/zip", content)
                : new DownloadedFile($"export-{job.Type}-{id:N}.jsonl", "application/x-ndjson", content);
        }, ct);
    }

    internal static ExportJobDto Dto(ExportJob j) => new(
        j.Id, j.Version, j.CreatedAt, j.CreatedBy, j.UpdatedAt, j.Type, j.Status, JsonSerializer.Deserialize<ExportFilters>(j.Filter, JsonDefaults.Options)!,
        j.StreamFromSeq is { } from && j.StreamToSeq is { } to ? new StreamRange(from, to) : null,
        j.Manifest is { } m ? JsonSerializer.Deserialize<ExportManifest>(m, JsonDefaults.Options) : null, j.CompletedAt, j.RetainUntil, j.FailureReason);
}

/// <summary>Builds the JSON Lines content of an export inside a tenant session (DEC-061). Used by the worker.</summary>
public static class ExportContent
{
    public sealed record Result(byte[] Content, long FromSequence, long ToSequence, int Rows);

    public static async Task<Result> BuildAsync(ITenantSession s, ExportJob job, CancellationToken ct)
    {
        var f = JsonSerializer.Deserialize<ExportFilters>(job.Filter, JsonDefaults.Options)!;
        var from = f.From ?? DateTimeOffset.UnixEpoch;
        var to = f.To ?? s.Now;
        var position = (await s.Db.Database.SqlQuery<long>($"SELECT last_sequence AS \"Value\" FROM ti.audit_stream WHERE tenant_id = {job.TenantId}")
            .ToListAsync(ct)).SingleOrDefault();
        var rows = job.Type switch
        {
            ExportType.Audit => (await s.Db.Database.SqlQuery<AuditRow>($"""
                SELECT sequence AS "Sequence", occurred_at AS "OccurredAt", actor_subject AS "Actor", event_type AS "EventType", object_type AS "ObjectType",
                       object_id AS "ObjectId", object_version AS "ObjectVersion", reason AS "Reason", before_state::text AS "Before", after_state::text AS "After",
                       encode(event_hash, 'hex') AS "EventHash"
                FROM ti.audit_event WHERE occurred_at >= {from} AND occurred_at < {to} ORDER BY sequence
                """).ToListAsync(ct)).Select(r => (object)r).ToList(),
            ExportType.Movements => (await s.Db.Database.SqlQuery<MovementRow>($"""
                SELECT m.id AS "Id", m.movement_type::text AS "Type", m.product_id AS "ProductId", m.lot_id AS "LotId", m.serial_id AS "SerialId",
                       m.source_bucket_id AS "SourceBucketId", m.destination_bucket_id AS "DestinationBucketId", m.base_qty AS "Quantity",
                       m.document_type::text AS "DocumentType", m.document_id AS "DocumentId", m.reservation_id AS "ReservationId", m.reason AS "Reason",
                       m.actor_subject AS "Actor", m.occurred_at AS "OccurredAt"
                FROM ti.stock_movement m
                WHERE m.occurred_at >= {from} AND m.occurred_at < {to}
                  AND ({f.ProductId}::uuid IS NULL OR m.product_id = {f.ProductId}) AND ({f.LotId}::uuid IS NULL OR m.lot_id = {f.LotId})
                  AND ({f.WarehouseId}::uuid IS NULL OR EXISTS (SELECT 1 FROM ti.stock_bucket b WHERE b.warehouse_id = {f.WarehouseId}
                        AND b.id IN (m.source_bucket_id, m.destination_bucket_id)))
                ORDER BY m.occurred_at, m.id
                """).ToListAsync(ct)).Select(r => (object)r).ToList(),
            ExportType.StockSnapshot => (await s.Db.Database.SqlQuery<BucketRow>($"""
                SELECT b.id AS "Id", b.warehouse_id AS "WarehouseId", b.bin_id AS "BinId", b.product_id AS "ProductId", b.lot_id AS "LotId",
                       b.serial_id AS "SerialId", b.quality_status::text AS "Quality", b.on_hand_qty AS "OnHand", b.reserved_qty AS "Reserved"
                FROM ti.stock_bucket b
                WHERE b.on_hand_qty > 0 AND ({f.WarehouseId}::uuid IS NULL OR b.warehouse_id = {f.WarehouseId})
                  AND ({f.ProductId}::uuid IS NULL OR b.product_id = {f.ProductId}) AND ({f.LotId}::uuid IS NULL OR b.lot_id = {f.LotId})
                ORDER BY b.warehouse_id, b.bin_id, b.product_id, b.id
                """).ToListAsync(ct)).Select(r => (object)r).ToList(),
            _ => throw new InvalidOperationException($"Export type {job.Type} is not generated yet."),
        };
        var sb = new StringBuilder();
        foreach (var row in rows)
            sb.Append(JsonSerializer.Serialize(row, row.GetType(), JsonDefaults.Options)).Append('\n');
        var (first, last) = job.Type == ExportType.Audit && rows.Count > 0
            ? (((AuditRow)rows[0]).Sequence, ((AuditRow)rows[^1]).Sequence)
            : (position, position);
        return new Result(Encoding.UTF8.GetBytes(sb.ToString()), first, last, rows.Count);
    }

    public sealed record AuditRow(long Sequence, DateTimeOffset OccurredAt, string Actor, string EventType, string ObjectType, Guid? ObjectId, int? ObjectVersion,
        string? Reason, string? Before, string? After, string EventHash);

    public sealed record MovementRow(Guid Id, string Type, Guid ProductId, Guid? LotId, Guid? SerialId, Guid? SourceBucketId, Guid? DestinationBucketId,
        decimal Quantity, string DocumentType, Guid DocumentId, Guid? ReservationId, string? Reason, string Actor, DateTimeOffset OccurredAt);

    public sealed record BucketRow(Guid Id, Guid WarehouseId, Guid BinId, Guid ProductId, Guid? LotId, Guid? SerialId, string Quality, decimal OnHand,
        decimal Reserved);
}
