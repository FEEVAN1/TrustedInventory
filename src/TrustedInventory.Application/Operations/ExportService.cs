public sealed record ExportFilters(DateTimeOffset? From, DateTimeOffset? To, Guid? WarehouseId, Guid? ProductId, Guid? LotId);

public sealed record CreateExport(ExportType Type, ExportFilters Filters);

public sealed record StreamRange(long FromSequence, long ToSequence);

